#!/usr/bin/env node
/**
 * Lifecycle code generator (#1693).
 *
 * Reads `scripts/lifecycle/lifecycle-spec.json` and writes:
 *   - backend/src/domain/lifecycle/generated.ts      (state enums, transitions, parsers)
 *   - frontend/src/shared/lib/lifecycle/generated.ts  (same surface, for the client)
 *   - backend/tests/contract-fixtures/lifecycle-transitions.json
 *                                                   (every ordered state pair, legal or not)
 *
 * Usage:
 *   node scripts/lifecycle/generate-lifecycle.mjs          # write outputs
 *   node scripts/lifecycle/generate-lifecycle.mjs --check  # exit 1 if any output has drifted
 *
 * The output is deterministic: the same spec always produces byte-identical files,
 * which is what makes `--check` a meaningful CI gate against hand edits.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SPEC_PATH = resolve(ROOT, "scripts/lifecycle/lifecycle-spec.json");

const OUTPUTS = [
  { path: "backend/src/domain/lifecycle/generated.ts", render: renderTypeScript },
  { path: "frontend/src/shared/lib/lifecycle/generated.ts", render: renderTypeScript },
  { path: "backend/tests/contract-fixtures/lifecycle-transitions.json", render: renderFixtures },
];

const TS_HEADER = [
  "// DO NOT EDIT. Generated from scripts/lifecycle/lifecycle-spec.json by",
  "// scripts/lifecycle/generate-lifecycle.mjs (#1693). Change the spec and regenerate;",
  "// `--check` fails when this file drifts from the spec.",
];

function pascal(key) {
  return key[0].toUpperCase() + key.slice(1);
}

function screamingSnake(key) {
  return key.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
}

function renderDomainTs(key, domain) {
  const P = pascal(key);
  const C = screamingSnake(key);
  const states = domain.states.map((s) => `  ${JSON.stringify(s)},`);
  const terminal = domain.terminal.map((s) => JSON.stringify(s)).join(", ");
  const transitions = domain.states.map(
    (from) => `  ${from}: [${domain.transitions[from].map((s) => JSON.stringify(s)).join(", ")}],`,
  );
  return [
    `export const ${C}_STATES = [`,
    ...states,
    "] as const;",
    `export type ${P}State = (typeof ${C}_STATES)[number];`,
    `export const ${C}_INITIAL_STATE: ${P}State = ${JSON.stringify(domain.initial)};`,
    `export const ${C}_TERMINAL_STATES: readonly ${P}State[] = [${terminal}];`,
    `export const ${C}_TRANSITIONS: Readonly<Record<${P}State, readonly ${P}State[]>> = {`,
    ...transitions,
    "};",
    `export function is${P}State(value: string): value is ${P}State {`,
    `  return (${C}_STATES as readonly string[]).includes(value);`,
    "}",
    `export function canTransition${P}(from: ${P}State, to: ${P}State): boolean {`,
    `  return ${C}_TRANSITIONS[from].includes(to);`,
    "}",
    `export type Parsed${P}State =`,
    `  | { kind: "known"; state: ${P}State }`,
    `  | { kind: "unknown"; raw: string };`,
    `export function parse${P}State(raw: string): Parsed${P}State {`,
    `  return is${P}State(raw) ? { kind: "known", state: raw } : { kind: "unknown", raw };`,
    "}",
  ].join("\n");
}

function renderTypeScript(spec) {
  const blocks = Object.entries(spec.domains).map(([key, domain]) => renderDomainTs(key, domain));
  return [...TS_HEADER, "", blocks.join("\n\n"), ""].join("\n");
}

function renderFixtures(spec) {
  const lines = [];
  lines.push("{");
  lines.push(
    `  "$comment": "Generated by scripts/lifecycle/generate-lifecycle.mjs (#1693). DO NOT EDIT. Every ordered state pair per domain, with whether the spec allows it.",`,
  );
  lines.push(`  "specVersion": ${spec.specVersion},`);
  lines.push('  "domains": {');
  const entries = Object.entries(spec.domains);
  entries.forEach(([key, domain], domainIndex) => {
    lines.push(`    ${JSON.stringify(key)}: {`);
    lines.push(`      "states": [${domain.states.map((s) => JSON.stringify(s)).join(", ")}],`);
    lines.push('      "transitions": [');
    const pairs = [];
    for (const from of domain.states) {
      for (const to of domain.states) {
        const legal = domain.transitions[from].includes(to);
        pairs.push(`        [${JSON.stringify(from)}, ${JSON.stringify(to)}, ${legal}]`);
      }
    }
    lines.push(pairs.join(",\n"));
    lines.push("      ]");
    lines.push(`    }${domainIndex === entries.length - 1 ? "" : ","}`);
  });
  lines.push("  }");
  lines.push("}");
  return lines.join("\n") + "\n";
}

function validateSpec(spec) {
  for (const [key, domain] of Object.entries(spec.domains)) {
    const known = new Set(domain.states);
    if (known.size !== domain.states.length) throw new Error(`${key}: duplicate states`);
    if (!known.has(domain.initial)) throw new Error(`${key}: initial state is not declared`);
    for (const terminal of domain.terminal) {
      if (!known.has(terminal)) throw new Error(`${key}: terminal ${terminal} is not declared`);
      if (domain.transitions[terminal].length !== 0) {
        throw new Error(`${key}: terminal state ${terminal} has outgoing transitions`);
      }
    }
    for (const from of domain.states) {
      if (!(from in domain.transitions)) throw new Error(`${key}: no transition row for ${from}`);
      for (const to of domain.transitions[from]) {
        if (!known.has(to)) throw new Error(`${key}: ${from} -> ${to} targets an undeclared state`);
        if (to === from) throw new Error(`${key}: self-loop ${from} -> ${to} is not allowed`);
      }
    }
  }
}

function main() {
  const check = process.argv.includes("--check");
  const spec = JSON.parse(readFileSync(SPEC_PATH, "utf8"));
  validateSpec(spec);

  let drifted = false;
  for (const output of OUTPUTS) {
    const target = resolve(ROOT, output.path);
    const next = output.render(spec);
    if (check) {
      const current = existsSync(target) ? readFileSync(target, "utf8") : null;
      if (current !== next) {
        drifted = true;
        console.error(`drift: ${output.path} does not match ${SPEC_PATH}`);
      }
      continue;
    }
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, next);
    console.log(`wrote ${output.path}`);
  }

  if (check && drifted) {
    console.error("Run `node scripts/lifecycle/generate-lifecycle.mjs` and commit the result.");
    process.exit(1);
  }
}

main();
